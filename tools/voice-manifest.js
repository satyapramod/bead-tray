// Writes js/data/voice-clips.js: which app lines have a recorded clip.
// usage: node tools/voice-manifest.js   (run after splitting new batches)
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const lines = require('./voice-lines.json');
const clips = {};
let missing = 0;
for (const l of lines) {
  if (fs.existsSync(path.join(root, 'audio/voice', l.id + '.m4a'))) clips[l.text] = l.id;
  else missing++;
}
fs.writeFileSync(path.join(root, 'js/data/voice-clips.js'),
`// Generated by tools/voice-manifest.js. Maps each spoken line to its recorded
// clip in audio/voice/ (Linda, ElevenLabs). Lines not listed use the browser voice.
// Also read by sw.js (no window there), hence the global lookup.
(function (g) {
  g.App = g.App || {};
  g.App.voiceClips = ${JSON.stringify(clips, null, 2)};
})(typeof window !== 'undefined' ? window : self);
`);
console.log(Object.keys(clips).length, 'clips,', missing, 'lines still without a clip');
